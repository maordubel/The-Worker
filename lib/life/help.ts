export function hintFor(state: LifeState, sceneId: string): string {
  const table = HINTS[state.chapter] ?? HINTS['1986']!
  if (state.chapterDone) return 'היום נגמר. תסגור את הכרטיס ותמשיך.'
  return table[sceneId] ?? table['*']
}

